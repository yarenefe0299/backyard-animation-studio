import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const probe = JSON.parse(await readFile('out/probe.json', 'utf8'));
const video = probe.streams.find(s => s.codec_name === 'h264');
assert.ok(video, 'H.264 video required');
assert.equal(video.width, 1080);
assert.equal(video.height, 1920);
assert.equal(video.r_frame_rate, '30/1');
assert.equal(Number(video.nb_frames), 300);
assert.ok(Math.abs(Number(probe.format.duration) - 10) < .05);
console.log('Verified: H.264, 1080×1920, 30 fps, 300 frames, 10 seconds.');
